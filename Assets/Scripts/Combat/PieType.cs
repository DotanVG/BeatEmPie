/// <summary>
/// Enum of all available pie types in BeatEmPie.
/// </summary>
public enum PieType
{
    Apple,          // Standard — always unlocked
    Cherry,         // Explosive AOE
    Blueberry,      // Freeze
    LemonMeringue,  // Chain lightning
    Strawberry,     // Homing
    Meat,           // Heavy damage
    Mushroom,       // Confusion
    Pumpkin,        // Ultimate AOE
    Chocolate,      // Damage over time
    Chili           // Fire trail
}
