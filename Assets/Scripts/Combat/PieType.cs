namespace BeatEmPie
{
    /// <summary>
    /// Enum of all available pie types in BeatEmPie.
    /// </summary>
    public enum PieType
    {
        Apple,          // Standard — always unlocked
        Cherry,         // Explosive AOE
        Blueberry,      // Freeze
        LemonMeringue,  // Chain lightning
        Strawberry,     // Homing
        Meat,           // Heavy damage + knockback
        Mushroom,       // Confusion
        Pumpkin,        // Ultimate large AOE
        Chocolate,      // Slow + damage over time
        Chili           // Burning fire trail
    }
}
